use crate::crypto::kdf::{
    hkdf_expand, hkdf_extract_sha256, hmac_sha1_mic, kdf, pbkdf2_pmk, prf_sha1,
};

#[test]
fn test_basic_kdf() {
    let key = [0x01u8; 32];
    let ctx = [0x02u8; 8];
    let result = kdf(&key, "Test Label", &ctx, 32);
    assert_eq!(result.len(), 32);
    let result2 = kdf(&key, "Test Label", &ctx, 32);
    assert_eq!(result, result2);
}

#[test]
fn test_hkdf_extract() {
    let prk = hkdf_extract_sha256(b"salt", b"ikm");
    assert_eq!(prk.len(), 32);
}

#[test]
fn test_hkdf_expand() {
    let prk = hkdf_extract_sha256(b"salt", b"ikm");
    let mut okm = [0u8; 48];
    hkdf_expand(&prk, b"test label", &mut okm);
    assert_eq!(okm.len(), 48);
}

/// M2/G3: WPA2-PSK PMK derivation against published vectors.
///
/// `PBKDF2(HMAC-SHA1, password, SSID, 4096, 256)`. The expected PMKs are
/// wpa_supplicant's passphrase test table
/// (`src/crypto/crypto_module_tests.c`, `passphrase_tests[]`) and are
/// cross-checked against an independent PBKDF2 implementation.
#[test]
fn test_pbkdf2_pmk_published_vectors() {
    // password "password", SSID "IEEE" (the classic 802.11 example).
    let pmk = pbkdf2_pmk("password", "IEEE");
    assert_eq!(
        pmk,
        [
            0xf4, 0x2c, 0x6f, 0xc5, 0x2d, 0xf0, 0xeb, 0xef, 0x9e, 0xbb, 0x4b,
            0x90, 0xb3, 0x8a, 0x5f, 0x90, 0x2e, 0x83, 0xfe, 0x1b, 0x13, 0x5a,
            0x70, 0xe2, 0x3a, 0xed, 0x76, 0x2e, 0x97, 0x10, 0xa1, 0x2e
        ]
    );
    let pmk = pbkdf2_pmk("ThisIsAPassword", "ThisIsASSID");
    assert_eq!(
        pmk,
        [
            0x0d, 0xc0, 0xd6, 0xeb, 0x90, 0x55, 0x5e, 0xd6, 0x41, 0x97, 0x56,
            0xb9, 0xa1, 0x5e, 0xc3, 0xe3, 0x20, 0x9b, 0x63, 0xdf, 0x70, 0x7d,
            0xd5, 0x08, 0xd1, 0x45, 0x81, 0xf8, 0x98, 0x27, 0x21, 0xaf
        ]
    );
    let pmk = pbkdf2_pmk(
        "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
        "ZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZ",
    );
    assert_eq!(
        pmk,
        [
            0xbe, 0xcb, 0x93, 0x86, 0x6b, 0xb8, 0xc3, 0x83, 0x2c, 0xb7, 0x77,
            0xc2, 0xf5, 0x59, 0x80, 0x7c, 0x8c, 0x59, 0xaf, 0xcb, 0x6e, 0xae,
            0x73, 0x48, 0x85, 0x00, 0x13, 0x00, 0xa9, 0x81, 0xcc, 0x62
        ]
    );
}

/// M2/G3: 802.11 PRF-384 PTK derivation (WPA2-PSK AKM) against a vector
/// computed with an independent HMAC-SHA1 PRF implementation.
///
/// `PTK = PRF-384(PMK, "Pairwise key expansion", min(AA,SPA) ||`
/// `max(AA,SPA) || min(ANonce,SNonce) || max(ANonce,SNonce))` with
/// `PRF(K, A, B) = HMAC-SHA1(K, A || 0 || B || i)` for i = 0, 1, ...
/// (802.11-2020 §12.7.1.2).
#[test]
fn test_prf_sha1_ptk_384() {
    let pmk = [
        0xf4, 0x2c, 0x6f, 0xc5, 0x2d, 0xf0, 0xeb, 0xef, 0x9e, 0xbb, 0x4b, 0x90,
        0xb3, 0x8a, 0x5f, 0x90, 0x2e, 0x83, 0xfe, 0x1b, 0x13, 0x5a, 0x70, 0xe2,
        0x3a, 0xed, 0x76, 0x2e, 0x97, 0x10, 0xa1, 0x2e,
    ];
    let anonce = [
        0x3c, 0x42, 0xb3, 0xf0, 0xd8, 0xe4, 0xec, 0x77, 0xee, 0x1f, 0x3a, 0x5e,
        0x0a, 0x6e, 0x3e, 0x99, 0xe6, 0xb3, 0xf8, 0xe8, 0xc1, 0xa8, 0xb2, 0xd4,
        0xa6, 0xf0, 0xe2, 0xc4, 0xa8, 0xb6, 0xd4, 0xf0,
    ];
    let snonce = [
        0x5c, 0x42, 0xb3, 0xf0, 0xd8, 0xe4, 0xec, 0x77, 0xee, 0x1f, 0x3a, 0x5e,
        0x0a, 0x6e, 0x3e, 0x99, 0xe6, 0xb3, 0xf8, 0xe8, 0xc1, 0xa8, 0xb2, 0xd4,
        0xa6, 0xf0, 0xe2, 0xc4, 0xa8, 0xb6, 0xd4, 0xf0,
    ];
    let aa = [0x02, 0x00, 0x00, 0x00, 0x00, 0x01]; // AP (authenticator)
    let spa = [0x02, 0x00, 0x00, 0x00, 0x00, 0x02]; // STA (supplicant)

    // Context: (min || max) of the MACs then of the nonces, mirroring
    // handshake4::FourWayState::derive_ptk.
    let mut context = Vec::with_capacity(12 + 64);
    context.extend_from_slice(&aa); // aa < spa
    context.extend_from_slice(&spa);
    context.extend_from_slice(&anonce); // anonce < snonce
    context.extend_from_slice(&snonce);
    let ptk = prf_sha1(&pmk, "Pairwise key expansion", &context, 48);
    assert_eq!(
        ptk,
        [
            0x06, 0x77, 0xa4, 0x76, 0x58, 0xc7, 0x1a, 0x43, 0xc0, 0x52, 0xdc,
            0x62, 0x28, 0xab, 0xc3, 0x96, 0x41, 0x84, 0xf4, 0x41, 0xfc, 0x69,
            0xdd, 0xb8, 0x20, 0x5f, 0xea, 0x24, 0x33, 0x99, 0x36, 0x18, 0xc6,
            0x02, 0xa2, 0x11, 0x8f, 0x24, 0xc3, 0x4f, 0x03, 0x8f, 0x78, 0x65,
            0x46, 0x09, 0xd5, 0x9f
        ]
    );
}

/// M2/G3: WPA2-PSK EAPOL-Key MIC against a vector computed with an
/// independent HMAC-SHA1 implementation:
/// `MIC = Truncate-128(HMAC-SHA1(KCK, data))` (KCK = PTK[0..16]).
#[test]
fn test_hmac_sha1_mic_128() {
    let kck = [
        0x06, 0x77, 0xa4, 0x76, 0x58, 0xc7, 0x1a, 0x43, 0xc0, 0x52, 0xdc, 0x62,
        0x28, 0xab, 0xc3, 0x96,
    ];
    let data: Vec<u8> = (0u8..32).collect();
    let mic = hmac_sha1_mic(&kck, &data);
    assert_eq!(
        mic,
        [
            0x19, 0x90, 0x44, 0xde, 0x98, 0xd6, 0x61, 0xdf, 0xd3, 0xba, 0x38,
            0x95, 0x99, 0x47, 0x72, 0xfe
        ]
    );
}
